"""
Video Compression using SVD + Distributed Video Coding (DVC)
Based on: "Video Compression based on Singular Value Decomposition
           and Distributed Video Coding" — S.Dhivya, M.Kannan (IJERD 2013)

========================================================================
HOW THIS DIFFERS FROM NAIVE SVD (svd.py):
  svd.py    → SVD applied to full frame per channel, no mean subtraction
  This file → Exactly follows the paper's two-stage pipeline:

  STAGE 1 — SVD (spatial compression, per GOP):
    1. Split video into GOPs of n frames (optimal: 21–31 per paper)
    2. Compute mean frame across all frames in the GOP
    3. Subtract mean from each frame: Fi' = Fi - Fmean
    4. Divide mean-subtracted frames into 8×8 blocks
    5. For each block position, stack the n blocks across frames → matrix
    6. Apply SVD to that stacked matrix
    7. Keep top-k eigenvectors (U, Vt) — sent ONCE as "group information"
    8. Each frame only stores/transmits its S coefficients → big saving

  STAGE 2 — DVC (temporal compression, Wyner-Ziv style):
    1. First frame of each GOP = key frame → encoded with H.264 (ffmpeg)
    2. Remaining frames = WZ frames
    3. Side information generated by linear interpolation between key frames
    4. Residual (WZ frame - side info) computed → quantized → simulates parity bits
    5. Decoder corrects SI using residual → reconstructed WZ frame
    6. Final output: key frames H.264 + corrected WZ frames → assembled video

Usage:
  python svd_paper_compression.py --input your_video.mp4
  python svd_paper_compression.py --input your_video.mp4 --rank 3 --gop 24
  python svd_paper_compression.py   # auto-generates test video
"""

