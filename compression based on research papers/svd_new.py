def compress_video(input_path, output_path, rank, gop_size, dvc_quant, plot_path):
    """
    Full SVD+DVC pipeline as described in the paper.
    Processes video GOP by GOP, applying SVD then DVC to each GOP.
    """
    print("\n" + "=" * 65)
    print("  SVD + DVC VIDEO COMPRESSION")
    print("  Based on Dhivya & Kannan, IJERD 2013")
    print("=" * 65)

    cap = cv2.VideoCapture(input_path)
    if not cap.isOpened():
        raise FileNotFoundError(f"Cannot open video: {input_path}")

    fps   = cap.get(cv2.CAP_PROP_FPS) or 25.0
    W     = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    H     = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    total = int(cap.get(cv2.CAP_PROP_FRAME_COUNT))
    dur   = total / fps if fps > 0 else 0

    print(f"\n  Input   : {input_path}")
    print(f"  Video   : {W}×{H}  |  {fps:.0f} fps  |  {total} frames  |  {dur:.1f}s")
    print(f"  GOP size: {gop_size}  |  SVD rank: {rank}  |  DVC quant: {dvc_quant}")
    print(f"  Theoretical SVD ratio: {svd_compression_ratio(gop_size, rank):.1f}x")
    print()

    # Read all frames into memory (for GOP processing)
    # For very large videos, this would need to be chunked
    print("  Reading frames...")
    all_frames = []
    while True:
        ret, frame = cap.read()
        if not ret:
            break
        all_frames.append(frame)
    cap.release()
    actual_total = len(all_frames)
    print(f"  Read {actual_total} frames.")

    # Output writer
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    raw_output = output_path.replace('.mp4', '_raw.mp4')
    writer = cv2.VideoWriter(raw_output, fourcc, fps, (W, H))

    # Metrics tracking
    all_psnr_svd  = []
    all_psnr_dvc  = []
    all_ratios    = []
    t0 = time.time()

    # Process GOP by GOP
    n_gops = (actual_total + gop_size - 1) // gop_size
    BAR = 36

    for gop_idx in range(n_gops):
        start = gop_idx * gop_size
        end   = min(start + gop_size, actual_total)
        gop   = all_frames[start:end]

        # ---- STAGE 1: SVD ----
        svd_frames, svd_info = compress_gop_svd(gop, rank)
        all_psnr_svd.extend(svd_info['psnr_list'])
        all_ratios.append(svd_info['ratio'])

        # ---- STAGE 2: DVC ----
        dvc_frames, dvc_info = compress_gop_dvc(svd_frames, dvc_quant)
        # DVC improves WZ frames; key frame unchanged
        all_psnr_dvc.extend([compute_psnr(gop[i], dvc_frames[i]) for i in range(len(gop))])

        # Write compressed frames
        for f in dvc_frames:
            writer.write(f)

        # Progress bar
        pct = (gop_idx + 1) / n_gops
        filled = int(BAR * pct)
        bar_str = '#' * filled + '-' * (BAR - filled)
        elapsed = time.time() - t0
        eta = (elapsed / (gop_idx + 1)) * (n_gops - gop_idx - 1) if gop_idx > 0 else 0
        avg_svd = np.mean(all_psnr_svd) if all_psnr_svd else 0
        avg_dvc = np.mean(all_psnr_dvc) if all_psnr_dvc else 0
        print(f"\r    [{bar_str}] GOP {gop_idx+1}/{n_gops}  "
              f"SVD PSNR~{avg_svd:.1f}dB  DVC PSNR~{avg_dvc:.1f}dB  ETA:{int(eta)}s  ",
              end='', flush=True)

    writer.release()
    print()

    elapsed = time.time() - t0
    mean_psnr_svd = float(np.mean(all_psnr_svd)) if all_psnr_svd else 0
    mean_psnr_dvc = float(np.mean(all_psnr_dvc)) if all_psnr_dvc else 0
    mean_ratio    = float(np.mean(all_ratios))    if all_ratios    else 0
    psnr_gain     = mean_psnr_dvc - mean_psnr_svd

    quality_svd = "excellent" if mean_psnr_svd >= 40 else ("good" if mean_psnr_svd >= 30 else "degraded")
    quality_dvc = "excellent" if mean_psnr_dvc >= 40 else ("good" if mean_psnr_dvc >= 30 else "degraded")

    print(f"\n  Done in {elapsed:.0f}s")
    print(f"  SVD  PSNR : {mean_psnr_svd:.2f} dB [{quality_svd}]")
    print(f"  DVC  PSNR : {mean_psnr_dvc:.2f} dB [{quality_dvc}]  (+{psnr_gain:.2f} dB from DVC)")
    print(f"  SVD ratio : {mean_ratio:.1f}x")

    orig_mb = os.path.getsize(input_path) / (1024 * 1024)

    # Re-encode with H.264 for actual file size reduction
    final_ok = False
    if shutil.which('ffmpeg'):
        print(f"\n  Re-encoding with H.264 (ffmpeg)...")
        orig_kbps = max(int((os.path.getsize(input_path) * 8) / (1024 * dur) * 0.7), 100) if dur > 0 else 500
        cmd = [
            'ffmpeg', '-y', '-i', raw_output,
            '-vcodec', 'libx264',
            '-b:v', f'{orig_kbps}k',
            '-maxrate', f'{orig_kbps * 2}k',
            '-bufsize', f'{orig_kbps * 4}k',
            '-preset', 'fast',
            '-movflags', '+faststart',
            output_path
        ]
        result = subprocess.run(cmd, capture_output=True, text=True)
        if result.returncode == 0 and os.path.exists(output_path):
            comp_mb = os.path.getsize(output_path) / (1024 * 1024)
            os.remove(raw_output)
            print(f"  Output  : {output_path}  ({comp_mb:.1f} MB)")
            print(f"  Size    : {orig_mb:.1f} MB → {comp_mb:.1f} MB  ({orig_mb/max(comp_mb,0.01):.1f}x reduction)")
            final_ok = True
        else:
            print(f"  ffmpeg failed — keeping raw output: {raw_output}")
    if not final_ok:
        print(f"  ffmpeg not found — raw output saved: {raw_output}")
        print(f"  Tip: ffmpeg -i {raw_output} -vcodec libx264 -crf 23 {output_path}")

    # Plot results
    print(f"\n  Generating results plot...")
    make_plot(mean_psnr_svd, mean_psnr_dvc, mean_ratio, rank,
              gop_size, all_psnr_svd, all_psnr_dvc, plot_path)

    print("\n" + "=" * 65)
    print(f"  GOP size    : {gop_size}")
    print(f"  SVD rank k  : {rank}")
    print(f"  SVD PSNR    : {mean_psnr_svd:.2f} dB [{quality_svd}]")
    print(f"  DVC PSNR    : {mean_psnr_dvc:.2f} dB [{quality_dvc}]")
    print(f"  PSNR gain   : +{psnr_gain:.2f} dB  (DVC over SVD alone)")
    print(f"  SVD ratio   : {mean_ratio:.1f}x")
    print("=" * 65)
    print("\n  All done!")


