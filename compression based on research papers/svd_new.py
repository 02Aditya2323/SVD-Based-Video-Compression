# ======================================================================
#  STAGE 1: SVD COMPRESSION (paper's method)
# ======================================================================

def compress_gop_svd(frames, k):
    """
    Compress a Group of Pictures (GOP) using the paper's SVD method.

    Paper's algorithm (Section III-A):
      - Compute mean frame across GOP
      - Subtract mean: Fi' = Fi - Fmean
      - Divide into 8×8 blocks
      - For each block position, stack blocks across all frames → matrix M (n × 64)
      - SVD(M) = U * S * Vt
      - Keep top-k singular vectors as shared "group information"
      - Each frame reconstructed from: Sk (coefficients) + shared U/Vt

    Args:
        frames : list of H×W×3 uint8 frames (one GOP)
        k      : SVD rank (number of singular values to keep)
    Returns:
        reconstructed_frames : list of H×W×3 uint8 frames (SVD-compressed GOP)
        compression_info     : dict with ratio, psnr_list
    """
    n = len(frames)
    H, W = frames[0].shape[:2]

    # Pad to multiple of 8 for block processing
    H_pad = ((H + 7) // 8) * 8
    W_pad = ((W + 7) // 8) * 8

    reconstructed = []
    psnr_vals = []

    # Process each channel independently (B, G, R)
    for c in range(3):
        # Extract channel for all frames, float32
        channel_stack = np.stack(
            [frames[i][:, :, c].astype(np.float32) for i in range(n)],
            axis=0  # shape: (n, H, W)
        )

        # --- Step 1: Compute mean frame and subtract ---
        mean_frame = channel_stack.mean(axis=0)  # (H, W)
        mean_subtracted = channel_stack - mean_frame[np.newaxis, :, :]  # (n, H, W)

        # --- Step 2: Pad to multiple of 8 ---
        ms_padded = np.pad(
            mean_subtracted,
            ((0, 0), (0, H_pad - H), (0, W_pad - W)),
            mode='constant'
        )  # (n, H_pad, W_pad)

        # --- Step 3: Apply SVD to each 8×8 block position across frames ---
        recon_padded = np.zeros_like(ms_padded)

        n_blocks_h = H_pad // 8
        n_blocks_w = W_pad // 8

        for bh in range(n_blocks_h):
            for bw in range(n_blocks_w):
                r0, r1 = bh * 8, (bh + 1) * 8
                c0, c1 = bw * 8, (bw + 1) * 8

                # Block matrix: shape (n, 64) — n frames, 64 pixels per block
                block_matrix = ms_padded[:, r0:r1, c0:c1].reshape(n, 64)

                # SVD: block_matrix = U * S * Vt
                # U: (n, n), S: (min(n,64),), Vt: (min(n,64), 64)
                rank_k = min(k, min(block_matrix.shape) - 1)
                rank_k = max(rank_k, 1)

                try:
                    U, S, Vt = np.linalg.svd(block_matrix, full_matrices=False)
                    # Truncate to rank k — this is what gets "stored/transmitted"
                    Uk  = U[:, :rank_k]   # (n, k) — frame coefficients per frame
                    Sk  = S[:rank_k]      # (k,)
                    Vtk = Vt[:rank_k, :]  # (k, 64) — GROUP INFORMATION (sent once)

                    # Reconstruct: low-rank approximation
                    recon_block = (Uk * Sk) @ Vtk  # (n, 64)
                except np.linalg.LinAlgError:
                    recon_block = block_matrix  # fallback: no compression

                recon_padded[:, r0:r1, c0:c1] = recon_block.reshape(n, 8, 8)

        # --- Step 4: Add mean frame back ---
        recon_channel = recon_padded[:, :H, :W] + mean_frame[np.newaxis, :, :]

        # Store per-channel results
        if c == 0:
            recon_channels = np.zeros((n, H, W, 3), dtype=np.float32)
        recon_channels[:, :, :, c] = recon_channel

    # Clip and convert to uint8
    recon_uint8 = np.clip(recon_channels, 0, 255).astype(np.uint8)

    # Compute PSNR for each frame
    for i in range(n):
        psnr_vals.append(compute_psnr(frames[i], recon_uint8[i]))

    # Compression ratio: paper stores k*(n+64+1) per block vs n*64 per block
    # Group information (Vtk) sent once, Sk per frame
    original_vals = n * 64
    svd_vals      = k * (n + 64 + 1)
    ratio = original_vals / max(svd_vals, 1)

    return [recon_uint8[i] for i in range(n)], {
        'ratio': ratio,
        'psnr_list': psnr_vals
    }


# ======================================================================
#  STAGE 2: DVC COMPRESSION (Wyner-Ziv style, simplified)
# ======================================================================

def compress_gop_dvc(frames, quant_step=8):
    """
    Apply DVC (Distributed Video Coding / Wyner-Ziv) to a GOP.

    Paper's DVC (Section III-B, simplified simulation):
      - Frame 0 = key frame → transmitted in full (H.264 in real codec)
      - Frames 1..n-1 = WZ frames
      - Side information (SI) generated by interpolating key frames
      - Residual = WZ frame - SI → quantized (simulates parity bits + correction)
      - Reconstruction = SI + dequantized residual

    In a real DVC system, a feedback channel requests more parity bits.
    Here we simulate this with quantized residuals (equivalent quality).

    Args:
        frames     : list of H×W×3 uint8 frames from SVD stage
        quant_step : quantization step for residuals (controls DVC compression)
    Returns:
        reconstructed : list of H×W×3 uint8 frames
        dvc_info      : dict with psnr improvement info
    """
    n = len(frames)
    if n == 1:
        return frames, {'psnr_before': [], 'psnr_after': []}

    psnr_before = []
    psnr_after  = []
    reconstructed = [frames[0]]  # Key frame: transmitted in full

    for i in range(1, n):
        # Side information: linear interpolation between nearest key frames
        # In a full DVC system this uses motion-compensated interpolation
        alpha = i / (n - 1)
        si = (1 - alpha) * frames[0].astype(np.float32) + alpha * frames[-1].astype(np.float32)
        si = np.clip(si, 0, 255)

        wz_frame = frames[i].astype(np.float32)

        # Residual = actual WZ frame - side information
        residual = wz_frame - si

        # Quantize residual (simulates parity bit compression)
        q_residual = np.round(residual / quant_step) * quant_step

        # Reconstruct: SI + corrected residual
        recon = np.clip(si + q_residual, 0, 255).astype(np.uint8)

        # Track PSNR: compare SI alone vs SI+residual correction
        psnr_before.append(compute_psnr(frames[i], np.clip(si, 0, 255).astype(np.uint8)))
        psnr_after.append(compute_psnr(frames[i], recon))

        reconstructed.append(recon)

    return reconstructed, {
        'psnr_before': psnr_before,
        'psnr_after':  psnr_after
    }


# ======================================================================
#  METRICS
# ======================================================================

def compute_psnr(original, compressed):
    """Peak Signal-to-Noise Ratio (dB). Higher = better quality."""
    mse = np.mean((original.astype(np.float32) - compressed.astype(np.float32)) ** 2)
    if mse == 0:
        return 60.0
    return float(10.0 * np.log10((255.0 ** 2) / mse))


def svd_compression_ratio(n_frames, k):
    """
    Theoretical compression ratio for the paper's block SVD scheme.
    Original per-block storage: n * 64
    SVD per-block storage:      k * (n + 64 + 1)
    """
    original = n_frames * 64
    compressed = k * (n_frames + 64 + 1)
    return original / max(compressed, 1)


